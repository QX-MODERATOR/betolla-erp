// Turns scripts/inventory/new-inventory.csv into supabase/migrations/046_new_inventory.sql.
// Run from the repo root:  node scripts/inventory/build-migration.mjs
//
// The CSV is the source of truth; edit it and re-run rather than editing the SQL by hand.
// A row whose sku already exists in the system is the same product under a new name: its price,
// cost, stock and reorder level are left as the system has them unless the CSV fills them in.
// A row with a new sku is a product the system has never had, so it must carry a price.
import {readFileSync, writeFileSync} from 'node:fs';

const CATEGORY_NAMES = {
  'plasma-hair-care': ['بلازما العناية بالشعر', 'Plasma Hair Care'],
  'professional-proteins': ['بروتينات الشعر الاحترافية', 'Professional Hair Proteins'],
  'morphosis-professional': ['مورفوزيس بروفيشنال الإيطالي', 'Morphosis Professional'],
  'argan-hair-care': ['العناية بالشعر بالأرجان', 'Argan Hair Care'],
  'hair-care': ['العناية بالشعر', 'Hair Care'],
  'electrical-styling': ['أجهزة التصفيف الكهربائية', 'Electrical Styling Tools'],
  'beto-lenses': ['عدسات بيتو ومستلزماتها', 'Beto Contact Lenses'],
};

// English names for the catalogue's English mode, word by word; anything unknown stays as written.
const EN = {
  'شامبو': 'Shampoo', 'بلسم': 'Conditioner', 'بلازما': 'Plasma', 'سيرم': 'Serum', 'ماسك': 'Mask',
  'ارجان': 'Argan', 'ريبير': 'Repair', 'هايدرو': 'Hydro', 'مور': 'Morphosis', 'صابليمز': 'Sublime',
  'ريستركشر': 'Restructure', 'ماراكوجا': 'Maracuja', 'اسود': 'Black', 'بلص': 'Plus', 'ثيرابي': 'Therapy',
  'ديفاي': 'Divay', 'بلكس': 'Plex', 'بلو': 'Blue', 'ذهبي': 'Gold', 'فضي': 'Silver', 'فيلر': 'Filler',
  'ليف': 'Leave', 'ان': 'In', 'كت': 'Kit', 'تساقط': 'Hair Loss', 'نهدي': 'Nahdi', 'ازرق': 'Blue',
  'مكبس': 'Hair Straightener', 'سشوار': 'Hair Dryer', 'ماك': 'Mac', 'تيربو': 'Turbo', 'ستار': 'Star',
  'تفتيح': 'Lightening', 'سشيت': 'Sachet', 'محلول': 'Solution', 'عدسات': 'Lenses', 'لتر': 'L', 'مل': 'ml', '+': '+',
};
const english = (name) => name.replace(/(^|[^\d]) لتر$/, '$1 1 لتر').split(' ').map((w) => EN[w] ?? w).join(' ').replace(/(\d+) (ml|L)\b/g, '$1$2');

function parseCsv(text) {
  const rows = [];
  for (const line of text.replace(/^﻿/, '').split(/\r?\n/)) {
    if (!line.trim()) continue;
    const cells = []; let cur = ''; let q = false;
    for (let i = 0; i < line.length; i++) {
      const ch = line[i];
      if (q) { if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++; } else if (ch === '"') q = false; else cur += ch; }
      else if (ch === '"') q = true; else if (ch === ',') { cells.push(cur); cur = ''; } else cur += ch;
    }
    cells.push(cur);
    rows.push(cells.map((c) => c.trim()));
  }
  return rows;
}

// '' means "keep what the system has" (NULL in the SQL); only a new product must say.
const money = (v, what, row) => {
  if (v === '') return null;
  if (!/^\d+(\.\d{1,3})?$/.test(v)) throw new Error(`row ${row}: ${what} "${v}" is not a price (e.g. 13 or 12.500)`);
  return Number(v).toFixed(3);
};
const count = (v, what, row) => {
  if (v === '') return null;
  if (!/^\d+$/.test(v)) throw new Error(`row ${row}: ${what} "${v}" is not a whole number`);
  return Number(v);
};
const sql = (s) => `'${String(s).replace(/'/g, "''")}'`;
const val = (v) => (v === null ? 'NULL' : v);

const [, , csvPath = 'scripts/inventory/new-inventory.csv', outPath = 'supabase/migrations/046_new_inventory.sql'] = process.argv;
const [header, ...data] = parseCsv(readFileSync(csvPath, 'utf8'));
if (header[0] !== 'sku') throw new Error('unexpected header: ' + header.join(','));
const products = data.map((r, i) => {
  const [sku, name, category, price, cost, stock, reorder] = r;
  const row = i + 2;
  if (!/^[A-Z0-9]+(-[A-Z0-9]+)+$/.test(sku)) throw new Error(`row ${row}: bad sku "${sku}"`);
  if (!name) throw new Error(`row ${row}: no name`);
  if (!CATEGORY_NAMES[category]) throw new Error(`row ${row}: unknown category "${category}"`);
  const p = {sku, name, category, price: money(price, 'سعر البيع', row), cost: money(cost, 'سعر التكلفة', row),
    stock: count(stock, 'الكمية', row), reorder: count(reorder, 'حد إعادة الطلب', row)};
  // BT- skus are minted for this catalogue, so the system cannot know their price.
  if (sku.startsWith('BT-') && p.price === null) throw new Error(`row ${row}: new product "${name}" has no price`);
  return p;
});
for (const key of ['sku', 'name']) {
  const seen = new Set();
  for (const p of products) { if (seen.has(p[key])) throw new Error(`duplicate ${key}: ${p[key]}`); seen.add(p[key]); }
}
const fresh = products.filter((p) => p.sku.startsWith('BT-'));
const kept = products.length - fresh.length;

const out = `-- The new catalogue: ${products.length} products (${kept} the system already had, ${fresh.length} new).
-- Generated by scripts/inventory/build-migration.mjs from scripts/inventory/new-inventory.csv
-- (the warehouse's list, checked against the live system with the sales team on 2026-09-23).
-- Do not edit by hand.
--
-- * A product the system already had keeps its row, SKU, price, stock and movement history and
--   only takes the warehouse's name and category. Keeping the row is what keeps its order lines,
--   the VIP price code, the free-sample codes and the plasma packages pointing at it.
-- * A new product is inserted with the price the sales team gave and an opening stock of 0: no
--   count was taken for these, and a guessed figure would be worse than an honest zero.
-- * Everything else is retired with is_active = false, as 020 did. inventory_movements is
--   ON DELETE RESTRICT, and the catalogue, order entry and business_resolve_product all filter
--   on is_active, so a retired product stops being offered but its history stays readable.
--   A package stays active only while every one of its bottles is still in the catalogue.
BEGIN;

INSERT INTO public.categories (slug, name_ar, name_en) VALUES
${Object.entries(CATEGORY_NAMES).map(([slug, [ar, en]]) => `  (${sql(slug)}, ${sql(ar)}, ${sql(en)})`).join(',\n')}
ON CONFLICT (slug) DO UPDATE SET is_active = true;

CREATE TEMP TABLE new_catalogue (sku text PRIMARY KEY, name_ar text, name_en text, category text,
  retail_price numeric(10,3), cost_price numeric(10,3), stock int, reorder int) ON COMMIT DROP;
INSERT INTO new_catalogue VALUES
${products.map((p) => `  (${sql(p.sku)}, ${sql(p.name)}, ${sql(english(p.name))}, ${sql(p.category)}, ${val(p.price)}, ${val(p.cost)}, ${val(p.stock)}, ${val(p.reorder)})`).join(',\n')};

DO $$
DECLARE missing text;
BEGIN
  SELECT string_agg(n.sku, ', ') INTO missing FROM new_catalogue n
  WHERE n.retail_price IS NULL AND NOT EXISTS (SELECT 1 FROM public.products p WHERE p.sku = n.sku);
  IF missing IS NOT NULL THEN
    RAISE EXCEPTION 'new catalogue: % should already exist but the system has no such sku', missing;
  END IF;
END $$;

-- The ones the system already had: new name and category, everything else as it was.
UPDATE public.products p SET name_ar = n.name_ar, name_en = n.name_en, category_id = c.id,
  retail_price = coalesce(n.retail_price, p.retail_price), cost_price = coalesce(n.cost_price, p.cost_price),
  is_active = true, updated_at = now()
FROM new_catalogue n JOIN public.categories c ON c.slug = n.category
WHERE p.sku = n.sku;

UPDATE public.inventory i SET quantity_on_hand = coalesce(n.stock, i.quantity_on_hand),
  reorder_level = coalesce(n.reorder, i.reorder_level), updated_at = now()
FROM new_catalogue n JOIN public.products p ON p.sku = n.sku
WHERE i.product_id = p.id AND (n.stock IS NOT NULL OR n.reorder IS NOT NULL);

-- The new ones.
INSERT INTO public.products (sku, name_ar, name_en, category_id, retail_price, cost_price, is_active)
SELECT n.sku, n.name_ar, n.name_en, c.id, n.retail_price, coalesce(n.cost_price, 0), true
FROM new_catalogue n JOIN public.categories c ON c.slug = n.category
WHERE NOT EXISTS (SELECT 1 FROM public.products p WHERE p.sku = n.sku);

-- Every catalogue product that is not a package gets a stock row (the free samples had none).
INSERT INTO public.inventory (product_id, quantity_on_hand, quantity_reserved, reorder_level)
SELECT p.id, coalesce(n.stock, 0), 0, coalesce(n.reorder, 5)
FROM new_catalogue n JOIN public.products p ON p.sku = n.sku
WHERE NOT EXISTS (SELECT 1 FROM public.product_bundles b WHERE b.bundle_product_id = p.id)
ON CONFLICT (product_id) DO NOTHING;

-- Retire the rest. A package survives only if all its bottles did.
UPDATE public.products p SET is_active = false, updated_at = now()
WHERE p.is_active AND p.sku NOT IN (SELECT sku FROM new_catalogue)
  AND NOT (EXISTS (SELECT 1 FROM public.product_bundles b WHERE b.bundle_product_id = p.id)
    AND NOT EXISTS (SELECT 1 FROM public.product_bundles b JOIN public.products c ON c.id = b.component_product_id
      WHERE b.bundle_product_id = p.id AND c.sku NOT IN (SELECT sku FROM new_catalogue)));

DO $$ BEGIN
  IF (SELECT count(*) FROM public.products p JOIN new_catalogue n ON n.sku = p.sku WHERE p.is_active) <> ${products.length} THEN
    RAISE EXCEPTION 'new catalogue: expected ${products.length} active products from the list';
  END IF;
END $$;

COMMIT;
`;
writeFileSync(outPath, out.replace(/\n/g, '\r\n'));
console.log(`046_new_inventory.sql: ${products.length} products, ${kept} kept, ${fresh.length} new`);
